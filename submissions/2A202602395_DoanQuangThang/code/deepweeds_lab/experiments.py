def release():
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def metric_row(y, probs):
    m = compute_metrics(y, probs.argmax(1), probs)
    return {k: m[k] for k in ('macro_f1', 'top1', 'balanced_acc', 'ece', 'nll')}


def strategy_loader(cfg, df, method):
    pcfg = json.loads((run_dir(cfg) / 'pretrained.json').read_text())
    size = 256 if method == 'resolution256' else cfg.img_size
    tfm = dataset.build_transforms(False, size, mean=pcfg.get('mean', dataset.IMAGENET_MEAN),
                                   std=pcfg.get('std', dataset.IMAGENET_STD))
    if method == 'fivecrop':
        # Retain the full resized image; the five 224 crops are generated by the strategy.
        from torchvision import transforms as T
        tfm = T.Compose([T.Resize(round(cfg.img_size * 256 / 224), interpolation=T.InterpolationMode.BICUBIC),
                         T.ToTensor(), T.Normalize(pcfg.get('mean', dataset.IMAGENET_MEAN),
                                                  pcfg.get('std', dataset.IMAGENET_STD))])
    return dataset.make_loader(df, cfg.images_dir, tfm, cfg.batch_size, False,
                               num_workers=cfg.num_workers, seed=cfg.seed)


def inference_trials(cfg, root):
    path = root / 'inference_results.json'
    rows = json.loads(path.read_text()) if path.exists() else []
    methods = ['single', 'hflip_prob', 'hflip_logit', 'fivecrop', 'resolution256', 'temperature', 'amp', 'fused']
    _, val_df, _ = dataset.load_split(cfg.labels_dir)
    model = load_checkpoint_model(cfg)
    latency_rows = []
    for i, method in enumerate(methods):
        if any(r['method'] == method for r in rows):
            continue
        if method == 'fused' and not any(isinstance(m, torch.nn.BatchNorm2d) for m in model.modules()):
            write_json(root / 'bn_fusion_not_applicable.json', {'backbone': cfg.backbone, 'reason': 'No BatchNorm2d in architecture'})
            continue
        measured_model = fuse_conv_bn(model) if method == 'fused' else model
        if method == 'fused' and sum(isinstance(m, torch.nn.BatchNorm2d) for m in measured_model.modules()) == sum(isinstance(m, torch.nn.BatchNorm2d) for m in model.modules()):
            write_json(root / 'bn_fusion_not_applicable.json', {'backbone': cfg.backbone, 'reason': 'No supported adjacent Conv-BN pair'})
            del measured_model
            continue
        if method == 'fused':
            x = torch.randn(2, 3, cfg.img_size, cfg.img_size, device=cfg.device)
            with torch.inference_mode():
                difference = float((model(x) - measured_model(x)).abs().max())
            if difference > 1e-4:
                raise ValueError(f'BN fusion changed logits: {difference}')
        try:
            loader = strategy_loader(cfg, val_df, method)
            names, y, z, probs = predict_strategy(measured_model, loader, cfg.device, method, cfg.img_size)
            temperature = fit_temperature(z, y) if method == 'temperature' else 1.0
            probs = apply_temperature(z, temperature)
            np.savez(root / f'I{i:02d}_val_logits.npz', filenames=names, labels=y, logits=z)
            timing = strategy_latency(measured_model, 1, cfg.img_size, method, device=cfg.device, iters=50, temperature=temperature)
            timing_batch = strategy_latency(measured_model, 32, cfg.img_size, method, device=cfg.device, iters=50, temperature=temperature)
            # Benchmark metadata includes method too: merge once, then set experiment fields.
            row = {**timing, **metric_row(y, probs),
                   'exp_id': f'I{i:02d}', 'method': method,
                   'checkpoint': str(run_dir(cfg) / 'best.pt'),
                   'K': 5 if method == 'fivecrop' else 2 if method.startswith('hflip') else 1,
                   'T': temperature, 'throughput_batch32': timing_batch['images_per_s'],
                   'latency_batch32': timing_batch}
            if method == 'fused':
                row['fusion_max_abs_error'] = difference
            rows.append(row); write_json(path, rows)
            print('Inference:', row, flush=True)
        except torch.cuda.OutOfMemoryError:
            # Preserve experiment failures explicitly rather than fabricate timings.
            failure_path = root / 'inference_failures.json'
            failures = json.loads(failure_path.read_text()) if failure_path.exists() else []
            failures.append({'method': method, 'reason': 'CUDA out of memory at declared batch size'})
            write_json(failure_path, failures); release()
        if method == 'fused':
            del measured_model; release()
    if len([r for r in rows if r['method'] != 'single']) < 4:
        raise RuntimeError('Fewer than four successful inference methods')
    if not any(r['method'] == 'temperature' for r in rows):
        raise RuntimeError('Calibration experiment missing')
    baseline = next(r['p50'] for r in rows if r['method'] == 'single')
    for row in rows:
        row['relative_cost'] = row['p50'] / baseline
    write_json(path, rows)
    del model; release()
    return rows


def final_predictions(cfg, method, exp_id, root):
    folder = root / 'final_cache' / exp_id / f'seed{cfg.seed}'
    folder.mkdir(parents=True, exist_ok=True)
    summary = folder / 'result.json'
    if summary.exists():
        return json.loads(summary.read_text())
    model = load_checkpoint_model(cfg)
    if method == 'fused':
        model = fuse_conv_bn(model)
    _, val_df, test_df = dataset.load_split(cfg.labels_dir)
    val_loader = strategy_loader(cfg, val_df, method)
    names_v, y_v, z_v, _ = predict_strategy(model, val_loader, cfg.device, method, cfg.img_size)
    T = fit_temperature(z_v, y_v) if exp_id != 'T00' else 1.0
    pv = apply_temperature(z_v, T)
    pred_dir = root / 'predictions'
    save_predictions(pred_dir / f'{exp_id}_seed{cfg.seed}_val.csv', names_v, y_v, pv)
    # Validation-dependent settings are persisted BEFORE creating the test loader.
    write_json(folder / 'locked_seed_config.json', {'config': asdict(cfg), 'method': method, 'T': T})
    final_timing = strategy_latency(model, 1, cfg.img_size, method, device=cfg.device, iters=50, temperature=T)
    archive = folder / 'test_logits.npz'
    if archive.exists():
        saved = np.load(archive); names, y, z = saved['filenames'].tolist(), saved['labels'], saved['logits']
    else:
        print('FINAL TEST ONCE:', exp_id, 'seed', cfg.seed, 'method', method, flush=True)
        loader = strategy_loader(cfg, test_df, method)
        names, y, z, _ = predict_strategy(model, loader, cfg.device, method, cfg.img_size)
        np.savez(archive, filenames=names, labels=y, logits=z)
    uncal = apply_temperature(z, 1); calibrated = apply_temperature(z, T)
    save_predictions(pred_dir / f'{exp_id}_seed{cfg.seed}_test.csv', names, y, calibrated)
    if exp_id == 'F01':
        # Same cached test forward; calibration comparison does not run test a second time.
        save_predictions(pred_dir / f'F01uncal_seed{cfg.seed}_test.csv', names, y, uncal)
    mv, mt = compute_metrics(y_v, pv.argmax(1), pv), compute_metrics(y, calibrated.argmax(1), calibrated)
    result = dict(exp_id=exp_id, seed=cfg.seed, backbone=cfg.backbone, method=method, T=T,
                  source_exp_id=cfg.exp_id, source_checkpoint=str(run_dir(cfg) / 'best.pt'),
                  latency=final_timing, p95_ms=final_timing['p95'],
                  macro_f1_val=mv['macro_f1'], **{f'{k}_test': mt[k] for k in ('macro_f1', 'top1', 'balanced_acc', 'ece')},
                  ece_uncal_test=compute_metrics(y, uncal.argmax(1), uncal)['ece'],
                  per_class={k: mt[k] for k in ('precision', 'recall', 'f1', 'support')}, confusion=mt['confusion'])
    # Reused seed-0 training still gets its own final curve and provenance.
    source_curve = Path(cfg.curves_dir) / f'{cfg.exp_id}_seed{cfg.seed}.png'
    target_curve = root / 'curves' / f'{exp_id}_seed{cfg.seed}.png'
    if source_curve != target_curve and not target_curve.exists():
        shutil.copy2(source_curve, target_curve)
    write_json(summary, result)
    del model; release()
    return json.loads(summary.read_text())


def execute(root='lab_output', epochs=10, batch_size=32, seeds=(0, 1, 2)):
    root = Path(root).resolve(); root.mkdir(parents=True, exist_ok=True)
    if len(seeds) < 3 or len(set(seeds)) != len(seeds):
        raise ValueError('Final comparison requires >=3 distinct seeds')
    if epochs < 10:
        raise ValueError('Full lab uses at least 10 epochs')
    start = time.time()
    write_json(root / 'execution_status.json', {'status': 'preparing', 'started_at': start})
    images, labels = prepare(root)
    if not torch.cuda.is_available():
        raise RuntimeError('Enable a Kaggle GPU before full lab execution')
    pipeline_checks(images, labels, root)
    cfg = Config(epochs=epochs, batch_size=batch_size, images_dir=images, labels_dir=labels,
                 out_dir=str(root / 'runs'), pred_dir=str(root / 'predictions'), curves_dir=str(root / 'curves'),
                 num_workers=2, device='cuda', seed=seeds[0])
    backbones = []
    for i, name in enumerate(models.SUGGESTED_BACKBONES, 1):
        c = replace(cfg, exp_id=f'B{i:02d}', backbone=name)
        write_json(root / 'execution_status.json', {'status': 'backbones', 'experiment': c.exp_id, 'started_at': start})
        row = run(c)
        m = load_checkpoint_model(c)
        row['latency_ms'] = strategy_latency(m, 1, c.img_size, device=c.device, iters=50)['p50']
        row['config'] = asdict(c); backbones.append(row)
        write_json(root / 'backbone_results.json', backbones)
        del m; release()
    winner = max(backbones, key=lambda r: r['macro_f1_val'])
    baseline = replace(cfg, exp_id='T00', backbone=winner['backbone'])
    # One axis at a time; each axis includes the shared baseline value.
    variants = [
        ('T00', 'baseline', {}), ('T01', 'A initialization', {'init': 'scratch'}),
        ('T02', 'A initialization', {'init': 'frozen'}), ('T03', 'B augmentation', {'aug': 'color'}),
        ('T04', 'B augmentation', {'mix': 'cutmix'}),
        ('T05', 'C loss', {'loss': 'ls', 'label_smoothing': 0.1}),
        ('T06', 'C loss', {'loss': 'focal'}), ('T07', 'C loss', {'loss': 'ce_weighted'}),
        ('T08', 'F regularization', {'ema_decay': 0.99}),
    ]
    training = []
    for exp_id, axis, changes in variants:
        c = replace(baseline, exp_id=exp_id, **changes)
        write_json(root / 'execution_status.json', {'status': 'training', 'experiment': exp_id, 'started_at': start})
        row = run(c); row.update(axis=axis, changes=json.dumps(changes), config=asdict(c))
        training.append(row); write_json(root / 'training_results.json', training); release()
    combined = {}
    for axis in ('A initialization', 'B augmentation', 'C loss', 'F regularization'):
        candidates = [r for r in training if r['axis'] == axis]
        best = max(candidates, key=lambda r: r['macro_f1_val'])
        if best['macro_f1_val'] > training[0]['macro_f1_val']:
            combined.update(json.loads(best['changes']))
    # Always test a combination; if individual gains are absent, label it exploratory.
    if len(combined) < 2:
        combined = {'mix': 'cutmix', 'loss': 'ls', 'label_smoothing': 0.1}
    c = replace(baseline, exp_id='T09', **combined)
    row = run(c); row.update(axis='combined', changes=json.dumps(combined), config=asdict(c))
    training.append(row); write_json(root / 'training_results.json', training)
    selected = max(training, key=lambda r: r['macro_f1_val'])
    selected_cfg = Config(**selected['config'])
    write_json(root / 'execution_status.json', {'status': 'inference', 'started_at': start})
    inference = inference_trials(selected_cfg, root)
    choice = max(inference, key=lambda r: (r['macro_f1'], -r['p95']))
    realtime_candidates = [r for r in inference if r['p95'] <= 100]
    realtime = max(realtime_candidates, key=lambda r: (r['macro_f1'], -r['p95'])) if realtime_candidates else None
    selection = {'realtime_method': realtime['method'] if realtime else None, 'backbone': winner['backbone'], 'training_config': selected['config'],
                 'baseline_config': asdict(baseline), 'inference': choice['method'],
                 'calibrate_final_on_val': True, 'seeds': list(seeds),
                 'selection_metric': 'validation macro-F1; ties broken by batch-1 p95 latency',
                 'selected_before_test': True}
    selection_path = root / 'selection_locked.json'
    if selection_path.exists() and json.loads(selection_path.read_text()) != selection:
        raise RuntimeError('Selection changed after lock; refusing another test evaluation')
    write_json(selection_path, selection)
    finals = []
    for seed in seeds:
        # Reuse existing seed-0 train runs; remaining seeds share exactly the selected recipe.
        final_cfg = selected_cfg if seed == seeds[0] else replace(selected_cfg, exp_id='F01', seed=seed)
        base_cfg = replace(baseline, seed=seed)
        write_json(root / 'execution_status.json', {'status': 'finals', 'seed': seed, 'started_at': start})
        run(final_cfg); run(base_cfg)
        finals.append(final_predictions(final_cfg, choice['method'], 'F01', root))
        finals.append(final_predictions(base_cfg, 'single', 'T00', root))
        if realtime:
            if realtime['method'] == choice['method']:
                finals.append(reuse_final_predictions(final_cfg, realtime['method'], 'F01', 'R01', root))
            else:
                finals.append(final_predictions(final_cfg, realtime['method'], 'R01', root))
        write_json(root / 'final_results.json', finals); release()
    # All test results are now fixed. Reporting never changes the selected configuration.
    from .reporting import create_artifacts
    create_artifacts(root, backbones, training, inference, finals, selection)
    eval_file = Path(sys.modules['eval'].__file__).resolve()
    for tag in (('F01', 'T00', 'R01') if realtime else ('F01', 'T00')):
        args = [sys.executable, str(eval_file), 'score', '--pred', str(root / 'predictions' / f'{tag}_seed*_test.csv'),
                '--test-csv', str(Path(labels) / 'test_subset0.csv'), '--labels', str(Path(labels) / 'labels.csv'),
                '--tag', tag, '--out', str(root / 'eval_out')]
        result = subprocess.run(args, check=True, text=True, capture_output=True)
        (root / f'eval_score_{tag}.txt').write_text(result.stdout); print(result.stdout, flush=True)
    grade = subprocess.run([sys.executable, str(eval_file), 'grade', '--final', str(root / 'predictions/F01_seed*_test.csv'),
        '--baseline', str(root / 'predictions/T00_seed*_test.csv'), '--uncal', str(root / 'predictions/F01uncal_seed*_test.csv'),
        '--final-val', str(root / 'predictions/F01_seed*_val.csv'), '--test-csv', str(Path(labels) / 'test_subset0.csv'),
        '--val-csv', str(Path(labels) / 'val_subset0.csv'),
        '--labels', str(Path(labels) / 'labels.csv'), '--latency-p95-ms', str(np.mean([r['p95_ms'] for r in finals if r['exp_id'] == ('R01' if realtime else 'F01')])), '--out', str(root / 'eval_out')],
        check=True, text=True, capture_output=True)
    (root / 'eval_grade.txt').write_text(grade.stdout); print(grade.stdout, flush=True)
    write_json(root / 'execution_status.json', {'status': 'complete', 'started_at': start, 'seconds': time.time() - start})
    print('LAB COMPLETE. Artifacts:', root, flush=True)
    return selection


def main():
    p = argparse.ArgumentParser(); p.add_argument('--output', default='lab_output')
    p.add_argument('--epochs', type=int, default=10); p.add_argument('--batch-size', type=int, default=32)
    args = p.parse_args(); execute(args.output, args.epochs, args.batch_size)


if __name__ == '__main__':
    main()
